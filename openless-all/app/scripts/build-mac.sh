#!/usr/bin/env bash
# One-shot build of the macOS release .app / .dmg.
#
# macOS NSXxxUsageDescription entries live in src-tauri/Info.plist and are merged by Tauri
# before generating the .app and .dmg, so an uploaded DMG never carries a stale Info.plist.
#
# Usage: run from the app/ directory
#     ./scripts/build-mac.sh           # build + sign + install to /Applications
#     INSTALL=0 ./scripts/build-mac.sh # build only, no install

set -euo pipefail

cd "$(dirname "$0")/.."

APP="src-tauri/target/release/bundle/macos/OpenLess.app"
INFO="$APP/Contents/Info.plist"
DMG_DIR="src-tauri/target/release/bundle/dmg"
INSTALL="${INSTALL:-1}"

if [ -z "${APPLE_CERTIFICATE:-}" ] && [ -z "${APPLE_SIGNING_IDENTITY:-}" ]; then
  export APPLE_SIGNING_IDENTITY="-"
  echo "▶ Certificado Apple não encontrado; usando assinatura ad-hoc (downloads ainda podem acionar o Gatekeeper)"
else
  echo "▶ Credenciais Apple detectadas; o Tauri fará a assinatura Developer ID e a notarização"
fi

source scripts/macos-build-env.sh
echo "▶ Cargo release codegen units: ${CARGO_PROFILE_RELEASE_CODEGEN_UNITS} (macOS only)"
echo "▶ Cargo release strip: ${CARGO_PROFILE_RELEASE_STRIP} (macOS only)"
echo "▶ Rust proc-macro host wrapper: ${RUSTC_WRAPPER}"

# Optional speech dependencies are downloaded into owned modules, never linked into this build.
echo "▶ tauri build"
TAURI_BUILD_ARGS=(build --ci)
case "$(uname -m)" in
  arm64)
    MAC_BUNDLE_ARCH="aarch64"
    TAURI_BUILD_ARGS+=(--config src-tauri/tauri.macos.conf.json)
    ;;
  x86_64)
    MAC_BUNDLE_ARCH="x64"
    ;;
  *)
    echo "✗ Arquitetura macOS não suportada: $(uname -m)"
    exit 1
    ;;
esac
if [ -n "${TAURI_SIGNING_PRIVATE_KEY:-}" ] || [ -n "${TAURI_SIGNING_PRIVATE_KEY_PATH:-}" ]; then
  TAURI_BUILD_ARGS+=(--config '{"bundle":{"createUpdaterArtifacts":true}}')
fi
APP_VERSION="$(node -p "require('./package.json').version")"
DMG_PATH="$DMG_DIR/OpenLess_${APP_VERSION}_${MAC_BUNDLE_ARCH}.dmg"

# Remove deliverables, keep Cargo caches. Hot builds reuse binaries with old timestamps, so
# bundle freshness can't be judged from compiled-file mtimes; a failed Tauri run must not leave
# the previous round's installer in place either.
rm -rf "$APP"
rm -f "$DMG_PATH" "${APP}.tar.gz" "${APP}.tar.gz.sig"
TAURI_BUILD_ARGS+=(-- --locked --timings)
if [ "$MAC_BUNDLE_ARCH" = "aarch64" ]; then
  # Tauri skips Finder AppleScript in CI. Write deterministic Finder metadata
  # into its temporary image before Tauri compresses and signs the final DMG.
  DMG_LAYOUT_ENV_DIR="$(mktemp -d "${TMPDIR:-/tmp}/openless-dmg-python.XXXXXX")"
  cleanup_dmg_environment() { rm -rf "$DMG_LAYOUT_ENV_DIR"; }
  trap cleanup_dmg_environment EXIT
  python3 -m venv "$DMG_LAYOUT_ENV_DIR"
  DMG_LAYOUT_PYTHON="$DMG_LAYOUT_ENV_DIR/bin/python3"
  "$DMG_LAYOUT_PYTHON" -m pip install --quiet --disable-pip-version-check \
    --only-binary=:all: --no-deps --require-hashes -r scripts/macos-dmg-requirements.txt
  "$DMG_LAYOUT_PYTHON" scripts/macos-dmg-layout.test.py
  CI=true TAURI_BUNDLER_DMG_IGNORE_CI=false \
    OPENLESS_DMG_LAYOUT_ROOT="$PWD" OPENLESS_DMG_LAYOUT_PYTHON="$DMG_LAYOUT_PYTHON" \
    OPENLESS_DMG_LAYOUT_STAMP="$DMG_LAYOUT_ENV_DIR/layout-applied" \
    PATH="$PWD/scripts/macos-dmg-bin:$PATH" npm run tauri -- "${TAURI_BUILD_ARGS[@]}"
  if [ ! -s "$DMG_LAYOUT_ENV_DIR/layout-applied" ]; then
    echo "✗ O Tauri não executou a etapa de layout do DMG; entrega interrompida"
    exit 1
  fi
  "$DMG_LAYOUT_PYTHON" scripts/macos-dmg-layout.py verify "$DMG_PATH"
  cleanup_dmg_environment
  trap - EXIT
else
  npm run tauri -- "${TAURI_BUILD_ARGS[@]}"
fi

if [ ! -f "$APP/Contents/MacOS/openless" ]; then
  echo "✗ $APP ausente ou não gerado nesta compilação (empacotamento incompleto); operação interrompida"
  exit 1
fi
# The DMG is always generated by Tauri (with the signing/notarization chain); a hand-rolled
# hdiutil DMG bypasses those steps and the bundle contract tests explicitly forbid it. Missing
# DMG = fail, no fallback.
if [ ! -f "$DMG_PATH" ]; then
  echo "✗ DMG desta compilação não encontrado: $DMG_PATH (o tauri build não concluiu o empacotamento)"
  exit 1
fi

echo "▶ Verificando Info.plist e assinatura"
/usr/libexec/PlistBuddy -c "Print :NSMicrophoneUsageDescription" "$INFO" > /dev/null
bash scripts/check-macos-audio-usage-description.sh "$INFO"
codesign -d --entitlements :- "$APP" 2> /dev/null | grep -q "com.apple.security.device.audio-input"
codesign --verify --deep --strict --verbose=2 "$APP" 2>&1 | tail -2

# A stale legacy resource must never leak into the new application bundle.
if [ -e "$APP/Contents/MacOS/mlx.metallib" ] || [ -e "$APP/Contents/Resources/mlx.metallib" ]; then
  echo "✗ O aplicativo contém recursos de execução MLX removidos"
  exit 1
fi
if [ -n "${TAURI_SIGNING_PRIVATE_KEY:-}" ] || [ -n "${TAURI_SIGNING_PRIVATE_KEY_PATH:-}" ]; then
  test -f "${APP}.tar.gz" || { echo "✗ Arquivo de atualização Tauri não encontrado"; exit 1; }
fi

HAS_DEVELOPER_ID=0
if [ -n "${APPLE_CERTIFICATE:-}" ] \
  || { [ -n "${APPLE_SIGNING_IDENTITY:-}" ] && [ "${APPLE_SIGNING_IDENTITY}" != "-" ]; }; then
  HAS_DEVELOPER_ID=1
fi
HAS_NOTARIZATION_CREDENTIALS=0
if { [ -n "${APPLE_ID:-}" ] \
  && [ -n "${APPLE_PASSWORD:-}" ] \
  && [ -n "${APPLE_TEAM_ID:-}" ]; } \
  || { [ -n "${APPLE_API_KEY:-}" ] && [ -n "${APPLE_API_ISSUER:-}" ]; }; then
  HAS_NOTARIZATION_CREDENTIALS=1
fi
if [ "$HAS_DEVELOPER_ID" = "1" ] && [ "$HAS_NOTARIZATION_CREDENTIALS" = "1" ]; then
  echo "▶ Verificando Gatekeeper e comprovantes de notarização"
  spctl --assess --type execute --verbose=2 "$APP"
  xcrun stapler validate "$APP"
  xcrun stapler validate "$DMG_PATH"
fi

echo "▶ Limpando atributos estendidos dos arquivos de distribuição"
# This only guarantees the CI/local build artifacts themselves are clean; browser downloads may
# still re-add quarantine. The real fix sparing users manual xattr is Developer ID signing +
# Apple notarization.
xattr -cr "$APP" 2> /dev/null || true
find "$DMG_DIR" -maxdepth 1 -name '*.dmg' -exec xattr -c {} \; 2> /dev/null || true

echo "▶ Verificando atributo de quarentena"
if xattr -pr com.apple.quarantine "$APP" > /dev/null 2>&1; then
  echo "✗ $APP ainda contém com.apple.quarantine"
  exit 1
fi
while IFS= read -r dmg; do
  if xattr -p com.apple.quarantine "$dmg" > /dev/null 2>&1; then
    echo "✗ $dmg ainda contém com.apple.quarantine"
    exit 1
  fi
done < <(find "$DMG_DIR" -maxdepth 1 -name '*.dmg' -print)

if [ "$INSTALL" = "1" ]; then
  echo "▶ Instalando em /Applications"
  pkill -f "OpenLess.app/Contents/MacOS/openless" 2> /dev/null || true
  sleep 1
  # TCC grants are bound to the designated requirement. An ad-hoc signature pins the cdhash,
  # which changes on each build, so old authorizations break immediately; without a reset,
  # "checked in System Settings" silently stops working. A stable signing identity keeps the
  # same requirement, so its grants survive the reinstall and are left alone.
  OLD_REQUIREMENT="$(codesign -d -r- /Applications/OpenLess.app 2> /dev/null || true)"
  NEW_REQUIREMENT="$(codesign -d -r- "$APP" 2> /dev/null || true)"
  if [ -z "$NEW_REQUIREMENT" ] || [ "$OLD_REQUIREMENT" != "$NEW_REQUIREMENT" ]; then
    echo "▶ Os requisitos de assinatura mudaram; redefinindo permissões de acessibilidade e microfone"
    tccutil reset Accessibility com.openless.app 2> /dev/null || true
    tccutil reset Microphone com.openless.app 2> /dev/null || true
  fi
  rm -rf /Applications/OpenLess.app
  cp -R "$APP" /Applications/
  xattr -dr com.apple.quarantine /Applications/OpenLess.app 2> /dev/null || true
  echo "✓ Instalado: /Applications/OpenLess.app"
  echo "  Para abrir: open /Applications/OpenLess.app"
fi
